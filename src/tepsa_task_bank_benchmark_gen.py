def _ceval_rows():
    rows = []
    n = 0
    for subj, items in CEVAL_BLOCKS:
        for idx, q, a, b, c, d, ans in items:
            n += 1
            opts = f"A.{a} B.{b} C.{c} D.{d}"
            text = f"（C-Eval·{subj}）{q} 选项：{opts}"
            sector = "code" if subj in ("computer_network", "operating_system", "college_programming") else "education"
            diff = "hard" if subj in ("law", "college_programming") else "medium"
            rows.append(
                {
                    "task_id": f"ceval-{n:03d}",
                    "task_text": text,
                    "task_source": f"HuggingFace ceval/ceval-exam config={subj} split=val row={idx}",
                    "sector": sector,
                    "expected_answer_hint": f"官方标准答案选项：{ans}（C-Eval CC BY-NC-SA 4.0；请引用 Huang et al. NeurIPS 2023）",
                    "risk_class": "low",
                    "difficulty_label": diff,
                }
            )
    return rows


def _cmmlu_rows():
    rows = []
    n = 0
    for subj, raw in CMMLU_CSV.items():
        rdr = csv.reader(io.StringIO(raw.strip()))
        next(rdr, None)
        for parts in rdr:
            if len(parts) < 7:
                continue
            _, q, a, b, c, d, ans = parts[0], parts[1], parts[2], parts[3], parts[4], parts[5], parts[6]
            n += 1
            text = f"（CMMLU·{subj}）{q} 选项：A.{a} B.{b} C.{c} D.{d}"
            rows.append(
                {
                    "task_id": f"cmmlu-{n:03d}",
                    "task_text": text,
                    "task_source": f"GitHub haonan-li/CMMLU data/dev/{subj}.csv (CC BY-NC-SA 4.0)",
                    "sector": "education",
                    "expected_answer_hint": f"标准答案：{ans.strip()}",
                    "risk_class": "low",
                    "difficulty_label": "medium",
                }
            )
    return rows


def main():
    rows = _ceval_rows() + _cmmlu_rows()
